export type Key = keyof typeof en;
const dicts = { en, es };

export function uiLang(setting?: string): "en" | "es" {
  if (setting === "en" || setting === "es") return setting;
  return (navigator.language || "en").toLowerCase().startsWith("es") ? "es" : "en";
}

export function translate(lang: "en" | "es", key: Key, vars?: Record<string, string | number>): string {
  let s = (dicts[lang] as Record<string, string>)[key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function useT() {
  const setting = useStore((s) => s.status?.settings.ui_language);
  const lang = uiLang(setting);
  return Object.assign((key: Key, vars?: Record<string, string | number>) => translate(lang, key, vars), { lang });
}

export function langName(code: string, ui: "en" | "es"): string {
  try {
    const name = new Intl.DisplayNames([ui], { type: "language" }).of(code === "jw" ? "jv" : code) || code;
    return name.charAt(0).toUpperCase() + name.slice(1);
  } catch {
    return code;
  }
}
